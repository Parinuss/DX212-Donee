test('rename is creator-only, rejects empty names, preserves identity/members and other groups', async () => {
  await as(B);
  await assert.rejects(() => rpc('select donee_rename_group($1,$2) result',[groupId,'Spoof']), /เฉพาะผู้สร้าง/);
  await as(C);
  await assert.rejects(() => rpc('select donee_rename_group($1,$2) result',[groupId,'Spoof']), /เฉพาะผู้สร้าง/);
  await assert.rejects(() => rpc('select donee_finish_delete_group($1) result',[groupId]), /เฉพาะผู้สร้าง/);
  await assert.rejects(() => rpc('select donee_begin_delete_group($1) result',[groupId]), /เฉพาะผู้สร้าง/);
  await as(A);
  await assert.rejects(() => rpc('select donee_rename_group($1,$2) result',[groupId,'   ']), /1–60/);
  await assert.rejects(() => rpc('select donee_rename_group($1,$2) result',[groupId,'\t\n']), /1–60/);
  await assert.rejects(() => rpc('select donee_rename_group($1,$2) result',[groupId,'x'.repeat(61)]), /1–60/);
  const renamed = await rpc('select donee_rename_group($1,$2) result',[groupId,'  Renamed  ']);
  assert.equal(renamed.name,'Renamed');
  await as(B);
  const group=(await rpc('select donee_list_groups() result')).find(g=>g.id===groupId);
  assert.equal(group.name,'Renamed'); assert.equal(group.members.length,2); assert.equal(group.invite_code,invite);
  await as(A);
  await assert.rejects(()=>db.query('update groups set name=$1 where id=$2',['Bypass',groupId]), /permission denied/);
});

test('partial attachment cleanup keeps group retryable; owner-only finish preserves unrelated data', async () => {
  await as(null,'postgres');
  await db.query("insert into messages(group_id,file_path) values($1,$2)",[groupId,`${groupId}/attached.pdf`]);
  await db.query("insert into storage.objects(bucket_id,name) values('chat-images',$1),('chat-images',$2),('chat-images',$3)", [`${groupId}/attached.pdf`,`${groupId}/orphan.png`,`${otherGroup}/safe.png`]);
  await as(B);
  await assert.rejects(()=>rpc('select donee_begin_delete_group($1) result',[groupId]), /เฉพาะผู้สร้าง/);
  await assert.rejects(()=>rpc('select donee_finish_delete_group($1) result',[groupId]), /เฉพาะผู้สร้าง/);
  assert.equal((await db.query('delete from storage.objects where name=$1 returning id',[`${groupId}/attached.pdf`])).rows.length,0);
  await as(A);
  await assert.rejects(()=>rpc('select donee_finish_delete_group($1) result',[groupId]), /เริ่มลบไฟล์/);
  const paths=await rpc('select donee_begin_delete_group($1) result',[groupId]);
  assert.deepEqual(paths,[`${groupId}/attached.pdf`,`${groupId}/orphan.png`]);
  await assert.rejects(()=>db.query('insert into messages(group_id,content) values($1,$2)',[groupId,'late']), /permission denied/);
  await assert.rejects(()=>rpc('select donee_save_group_task($1,null,$2,now(),$3,$4,false) result',[groupId,'Late','Group','Low']), /กำลังถูกลบ/);
  await assert.rejects(()=>rpc('select donee_join_group($1) result',[invite]), /กำลังถูกลบ/);
  await assert.rejects(()=>rpc('select donee_rename_group($1,$2) result',[groupId,'Late']), /กำลังถูกลบ/);
  // Emulate Storage API metadata removal, not SQL used by the app.
  assert.equal((await db.query('delete from storage.objects where name=$1 returning id',[paths[0]])).rows.length,1);
  await assert.rejects(()=>rpc('select donee_finish_delete_group($1) result',[groupId]), /ยังลบไฟล์แนบไม่ครบ/);
  assert.equal((await db.query('select * from groups where id=$1',[groupId])).rows.length,1);
  assert.deepEqual(await rpc('select donee_begin_delete_group($1) result',[groupId]),[paths[1]]);
  await as(null,'postgres');
  await assert.rejects(()=>db.query("insert into storage.objects(bucket_id,name) values('chat-images',$1)",[`${groupId}/late.png`]), /กำลังถูกลบ/);
  await assert.rejects(()=>db.query('insert into messages(group_id,content) values($1,$2)',[groupId,'late']), /กำลังถูกลบ/);
  await as(A);
  await db.query('delete from storage.objects where name=$1',[paths[1]]);
  assert.equal(await rpc('select donee_finish_delete_group($1) result',[groupId]),true);
  await as(null,'postgres');
  for (const table of ['groups','tasks','messages','group_members']) {
    const column=table==='groups'?'id':'group_id';
    assert.equal((await db.query(`select * from ${table} where ${column}=$1`,[groupId])).rows.length,0);
  }
  assert.equal((await db.query('select * from profiles')).rows.length,3);
  assert.equal((await db.query('select * from groups where id=$1',[otherGroup])).rows.length,1);
  assert.equal((await db.query('select * from tasks where group_id=$1',[otherGroup])).rows.length,1);
  assert.equal((await db.query('select * from tasks where group_id is null')).rows.length,1);
  assert.equal((await db.query('select * from storage.objects')).rows.length,1);
  await as(null,'anon');
  for (const sql of ['select donee_rename_group(1,\'X\')','select donee_begin_delete_group(1)','select donee_finish_delete_group(1)']) await assert.rejects(()=>db.query(sql), /permission denied/);
});
